"""Generate TypeScript types from the engine and API dataclasses.

    python scripts/gen_ts_types.py ../web/src/api/types.generated.ts

Decimals and dates travel as strings, enums as string unions, tuples as arrays. Fields with a
default value are optional (`?`) in request types, which may omit them; response-only types
always carry every field.
"""

from __future__ import annotations

import sys
from dataclasses import MISSING, fields, is_dataclass
from datetime import date
from decimal import Decimal
from enum import Enum
from pathlib import Path
from types import NoneType, UnionType
from typing import Any, Union, get_args, get_origin, get_type_hints

from engine_api import models
from payroll_engine.components import Component
from payroll_engine.models import Payslip, PayslipInput
from payroll_engine.rules import RuleEntry
from payroll_engine.termination import TerminationResult

# Classes reachable from these are request bodies: fields with defaults may be omitted.
INPUT_ROOTS: tuple[type[Any], ...] = (
    PayslipInput,
    models.EmployeeRecord,
    models.MonthEntry,
    models.TerminationRequest,
    models.EntryBatch,
    models.NewCompany,
    models.Company,
    models.Assignees,
    models.PreviewRequest,
)

ROOTS: tuple[type[Any], ...] = (
    PayslipInput,
    Payslip,
    TerminationResult,
    Component,
    RuleEntry,
    models.Firm,
    models.EmployeeRecord,
    models.MonthEntry,
    models.MonthInfo,
    models.MonthView,
    models.RunResult,
    models.CompanySummary,
    models.CorrectionDiff,
    models.AnnualResult,
    models.TerminationRequest,
    models.Holiday,
    models.CoverageGap,
    models.RulesMeta,
    models.EntryBatch,
    models.NewCompany,
    models.YearData,
    models.Liability,
    models.User,
    models.TermChange,
    models.OpenMonths,
    models.PortfolioRow,
    models.MonthPreview,
    models.Assignees,
    models.PreviewRequest,
)


def reachable(roots: tuple[type[Any], ...]) -> set[type[Any]]:
    seen: set[type[Any]] = set()

    def visit(tp: Any) -> None:
        for arg in get_args(tp):
            visit(arg)
        if isinstance(tp, type) and is_dataclass(tp) and tp not in seen:
            seen.add(tp)
            for hint in get_type_hints(tp).values():
                visit(hint)

    for root in roots:
        visit(root)
    return seen


class Generator:
    def __init__(self) -> None:
        self.interfaces: dict[str, str] = {}
        self.enums: dict[str, str] = {}
        self.inputs = reachable(INPUT_ROOTS)

    def ts(self, tp: Any) -> str:
        origin = get_origin(tp)
        if origin in (Union, UnionType):
            parts = [self.ts(a) for a in get_args(tp) if a is not NoneType]
            nullable = NoneType in get_args(tp)
            return " | ".join(parts + (["null"] if nullable else []))
        if origin is tuple:
            args = get_args(tp)
            if len(args) == 2 and args[1] is Ellipsis:
                inner = self.ts(args[0])
                return f"({inner})[]" if "|" in inner else f"{inner}[]"
            return "[" + ", ".join(self.ts(a) for a in args) + "]"
        if origin is dict:
            return "Record<string, unknown>"
        if tp is Any:
            return "unknown"
        if tp in (Decimal, date, str):
            return "string"
        if tp is int:
            return "number"
        if tp is bool:
            return "boolean"
        if isinstance(tp, type) and issubclass(tp, Enum):
            self.enums.setdefault(
                tp.__name__, " | ".join(f'"{m.value}"' for m in tp)  # type: ignore[attr-defined]
            )
            return tp.__name__
        if isinstance(tp, type) and is_dataclass(tp):
            self.add(tp)
            return tp.__name__
        raise TypeError(f"unsupported type {tp!r}")

    def add(self, cls: type[Any]) -> None:
        if cls.__name__ in self.interfaces:
            return
        self.interfaces[cls.__name__] = ""  # reserve to stop recursion
        hints = get_type_hints(cls)
        lines = []
        for f in fields(cls):
            has_default = f.default is not MISSING or f.default_factory is not MISSING
            optional = has_default and cls in self.inputs
            lines.append(f"  {f.name}{'?' if optional else ''}: {self.ts(hints[f.name])};")
        self.interfaces[cls.__name__] = (
            f"export interface {cls.__name__} {{\n" + "\n".join(lines) + "\n}"
        )

    def render(self) -> str:
        head = "// Generated by engine-api/scripts/gen_ts_types.py - do not edit by hand.\n"
        enums = [f"export type {name} = {values};" for name, values in sorted(self.enums.items())]
        interfaces = [self.interfaces[name] for name in sorted(self.interfaces)]
        return head + "\n" + "\n".join(enums) + "\n\n" + "\n\n".join(interfaces) + "\n"


def main(out: str) -> None:
    gen = Generator()
    for root in ROOTS:
        gen.add(root)
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(gen.render(), "utf-8")
    print(f"wrote {len(gen.interfaces)} interfaces, {len(gen.enums)} enums to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
